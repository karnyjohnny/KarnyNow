#!/usr/bin/env python3
"""dtls_openssl_check.py — the R3-B cross-implementation gate (SANDBOX ONLY).

The two-implementations rule at the DTLS layer: our kn_dtls client (mbedTLS)
must complete a real DTLS 1.2 handshake against an INDEPENDENT stack —
OpenSSL's `s_server -dtls1_2`, with a server certificate generated by
OpenSSL and pinned by its SHA-256 fingerprint exactly like the rig's
DESCRIBE fingerprint is pinned. This leg proves, against a non-mbedTLS
peer: the ClientHello shape, the HelloVerifyRequest cookie round (OpenSSL
sends one by default), cipher negotiation with our ECDSA P-256 identity,
and the Finished/verify path.

The Win7 target has no OpenSSL — its authority is test_kndtls's own
battery (in-test mbedTLS server, mutual pinning, loss legs) under T10.
This script is a sandbox gate, run each round next to ctest.

Usage:
    python3 tools/dtls_openssl_check.py [--binary build/mb/test_kndtls]

Requires: a CMake mbedtls build of test_kndtls (the --openssl mode),
openssl(1) with DTLS 1.2 support. Exit 0 = PASS.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def fail(msg):
    print("DTLS-OPENSSL CHECK FAIL: %s" % msg)
    sys.exit(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary",
                    default=os.path.join(ROOT, "build", "mb", "test_kndtls"))
    args = ap.parse_args()

    if not os.path.isfile(args.binary):
        fail("client binary %s missing — run the CMake mbedtls build first"
             % args.binary)

    workdir = tempfile.mkdtemp(prefix="kn-dtls-openssl-")
    key = os.path.join(workdir, "server.key")
    crt = os.path.join(workdir, "server.crt")

    # 1. an OpenSSL-generated ECDSA P-256 self-signed server cert —
    #    the same algorithm/shape family as our kn_cert identity
    r = subprocess.run(
        ["openssl", "req", "-x509", "-newkey", "ec",
         "-pkeyopt", "ec_paramgen_curve:prime256v1",
         "-keyout", key, "-out", crt, "-days", "1", "-nodes",
         "-subj", "/CN=kn-dtls-interop"],
        capture_output=True, text=True)
    if r.returncode != 0:
        fail("openssl req: %s" % r.stderr.strip()[:300])

    # 2. its SHA-256 fingerprint, in the announced colon-uppercase-hex form
    r = subprocess.run(["openssl", "x509", "-in", crt, "-noout",
                        "-fingerprint", "-sha256"],
                       capture_output=True, text=True)
    m = re.search(r"=\s*([0-9A-Fa-f:]{95})", r.stdout)
    if not m:
        fail("cannot parse fingerprint from: %r" % r.stdout[:200])
    fp = m.group(1).upper()

    # 3. the server: DTLS 1.2 only, UDP. No client-cert request (plain
    #    s_server default) — this leg proves the interop of OUR client
    #    half (ClientHello, HVR cookie round, ECDHE key share, Finished)
    #    against an independent stack; the mutual-pinning shape is
    #    covered by test_kndtls's own in-test server battery.
    port = 45454
    srv = subprocess.Popen(
        ["openssl", "s_server", "-dtls1_2", "-accept", str(port),
         "-cert", crt, "-key", key, "-quiet"],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE)
    time.sleep(0.6)
    if srv.poll() is not None:
        err = srv.stderr.read().decode(errors="replace") if srv.stderr else ""
        fail("s_server exited early: %s" % err.strip()[:300])

    # 4. the client leg (test_kndtls --openssl): pinned to the OpenSSL fp
    try:
        r = subprocess.run([args.binary, "--openssl", str(port), fp],
                           capture_output=True, text=True, timeout=60)
        out = (r.stdout or "") + (r.stderr or "")
        print(out.strip())
        if r.returncode != 0 or "openssl-interop: PASS" not in out:
            fail("client leg rc=%d" % r.returncode)
    finally:
        srv.kill()
        try:
            srv.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass

    print("DTLS-OPENSSL CHECK PASS (independent stack accepted our "
          "ClientHello/cookie/cert/Finished; pin=%s...)" % fp[:17])
    sys.exit(0)


if __name__ == "__main__":
    main()
